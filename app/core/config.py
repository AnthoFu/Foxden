"""
Configuration management for Minecraft server.
Handles server.properties parsing/updating, eula.txt, and JVM launch flags.
"""

from pathlib import Path
from typing import Dict, Optional


class ConfigManager:
    def __init__(self, server_dir: Path) -> None:
        self.server_dir = Path(server_dir).resolve()

    @property
    def properties_path(self) -> Path:
        return self.server_dir / "server.properties"

    @property
    def eula_path(self) -> Path:
        return self.server_dir / "eula.txt"

    def ensure_eula_accepted(self) -> None:
        """Ensures eula.txt exists with eula=true."""
        self.server_dir.mkdir(parents=True, exist_ok=True)
        self.eula_path.write_text("eula=true\n", encoding="utf-8")

    def read_properties(self) -> Dict[str, str]:
        """Reads server.properties into a dictionary."""
        if not self.properties_path.exists():
            return {}

        properties: Dict[str, str] = {}
        for line in self.properties_path.read_text(encoding="utf-8", errors="replace").splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if "=" in line:
                key, val = line.split("=", 1)
                properties[key.strip()] = val.strip()
        return properties

    def update_properties(self, updates: Dict[str, str]) -> None:
        """Updates specific keys in server.properties while preserving unedited keys and comments."""
        if not self.properties_path.exists():
            # Create fresh properties file
            lines = ["# Minecraft server properties", "# Generated by Foxden"]
            for k, v in updates.items():
                lines.append(f"{k}={v}")
            self.properties_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
            return

        lines = self.properties_path.read_text(encoding="utf-8", errors="replace").splitlines()
        updated_keys = set()
        new_lines = []

        for line in lines:
            stripped = line.strip()
            if stripped and not stripped.startswith("#") and "=" in stripped:
                key, _ = stripped.split("=", 1)
                key = key.strip()
                if key in updates:
                    new_lines.append(f"{key}={updates[key]}")
                    updated_keys.add(key)
                    continue
            new_lines.append(line)

        # Append any remaining keys that weren't in the original file
        for k, v in updates.items():
            if k not in updated_keys:
                new_lines.append(f"{k}={v}")

        self.properties_path.write_text("\n".join(new_lines) + "\n", encoding="utf-8")

    def get_summary_settings(self) -> dict:
        """Returns friendly common settings for the dashboard."""
        props = self.read_properties()
        return {
            "server_port": int(props.get("server-port", 25565)),
            "motd": props.get("motd", "A Minecraft Server"),
            "max_players": int(props.get("max-players", 20)),
            "difficulty": props.get("difficulty", "easy"),
            "gamemode": props.get("gamemode", "survival"),
            "online_mode": props.get("online-mode", "true").lower() == "true",
            "pvp": props.get("pvp", "true").lower() == "true",
            "white_list": props.get("white-list", "false").lower() == "true",
            "view_distance": int(props.get("view-distance", 10)),
        }
